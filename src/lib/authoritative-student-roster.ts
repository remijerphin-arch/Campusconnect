export function getAuthoritativeStudentByEmail(email: string) {
  return AUTHORITATIVE_STUDENT_ROSTER.find(s => s.email.toLowerCase() === email.toLowerCase()) || null;
}

export function getAuthoritativeStudentByRegisterNumber(registerNumber: string) {
  return AUTHORITATIVE_STUDENT_ROSTER.find(s => s.registerNumber === registerNumber) || null;
}

export function searchAuthoritativeStudents(query: string) {
  if (!query.trim()) return AUTHORITATIVE_STUDENT_ROSTER;
  
  const lowerQuery = query.toLowerCase();
  return AUTHORITATIVE_STUDENT_ROSTER.filter(student =>
    student.fullName.toLowerCase().includes(lowerQuery) ||
    student.registerNumber.toLowerCase().includes(lowerQuery) ||
    student.email.toLowerCase().includes(lowerQuery)
  );
}
